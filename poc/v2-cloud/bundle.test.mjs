import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { URL } from "node:url";
import { createHash } from "node:crypto";
import { renderBundle, stripTransaction, checkBundle, sources, templates } from "./bundle.mjs";
import { checkReadiness } from "./preflight.mjs";
const read = (path) => readFileSync(new URL("../../" + path, import.meta.url), "utf8");
const files = renderBundle();
const plan = JSON.parse(files["manifest.json"]);
const now = new Date("2026-11-08T23:00:00Z");
const observed = {
  projectRef: plan.projectRef,
  plan: "free",
  planSource: "user-dashboard",
  usageObservedAt: now.toISOString(),
  remainingBytes: { ...plan.requiredRemainingBytes },
  sessionPolicyObservedAt: now.toISOString(),
  sessionPolicy: { ...plan.sessionPolicy },
  authSchemaVerified: true,
  migrationOwnerReviewed: true,
  gatewayVerified: true,
  privateStorageVerified: true,
  rollbackReviewed: true,
  targetInspectedAt: now.toISOString(),
  deploymentCollisionFree: true,
  dataApiPrivateSchemasHidden: true,
  bundleReviewed: true,
  bundleManifestSha256: createHash("sha256").update(files["manifest.json"]).digest("hex"),
};
test("build reproducible bytes", () => assert.deepEqual(renderBundle(), files));
test("install has one outer commit boundary", () => {
  assert.equal((files["install.sql"].match(/^BEGIN;$/gm) || []).length, 1);
  assert.equal((files["install.sql"].match(/^COMMIT;$/gm) || []).length, 1);
});
test("module order is guard metadata recovery", () =>
  assert.deepEqual(
    plan.sources.map((s) => s.path),
    sources,
  ));
test("all source hashes identify exact bytes", () => {
  for (const s of plan.sources)
    assert.equal(createHash("sha256").update(read(s.path)).digest("hex"), s.sha256);
});
test("all generated artifact hashes match", () => {
  for (const [name, digest] of Object.entries(plan.artifactSha256))
    assert.equal(createHash("sha256").update(files[name]).digest("hex"), digest);
});
test("bundle covers both schemas six tables and four RPCs", () => {
  assert.equal(plan.objects.schemas.length, 2);
  assert.equal(plan.objects.tables.length, 6);
  assert.equal(plan.objects.publicFunctions.length, 4);
  assert.equal(plan.objects.privateFunctions.length, 3);
});
test("never auto applies or raises budget", () => {
  assert.equal(plan.autoApply, false);
  assert.equal(plan.monthlyBudgetKRW, 0);
});
test("generated uninstall has no cascade or auth data changes", () => {
  assert.ok(!/\bCASCADE\b/i.test(files["rollback.sql"]));
  assert.ok(!/\b(DELETE|TRUNCATE)\b/i.test(files["rollback.sql"]));
  assert.ok(files["rollback.sql"].includes("BUNDLE_DATA_PRESENT"));
});
test("all tables guarded before removal", () => {
  for (const t of plan.objects.tables)
    assert.ok(files["rollback.sql"].includes("EXISTS(SELECT 1 FROM " + t + ")"));
});
test("pause and resume contain no drop/delete/table changes", () => {
  for (const n of ["pause.sql", "resume.sql"])
    assert.ok(!/\b(DROP|DELETE|TRUNCATE|UPDATE|INSERT|ALTER)\b/i.test(files[n]));
});
test("strip preserves internal PLpgSQL body", () =>
  assert.ok(
    stripTransaction("-- c\nBEGIN;\nDO $$BEGIN RAISE NOTICE 'ok'; END$$;\nCOMMIT;").includes("DO $$BEGIN"),
  ));
test("missing transaction wrapper rejected", () => assert.throws(() => stripTransaction("SELECT 1;")));
test("nested transaction boundary rejected", () =>
  assert.throws(() => stripTransaction("BEGIN;\nSELECT 1;\nCOMMIT;\nSELECT 2;\nCOMMIT;")));
test("source changes produce different manifest and install hash", () => {
  const changed = renderBundle((p) => (p === sources[0] ? "-- change\n" : "") + read(p));
  assert.notEqual(changed["manifest.json"], files["manifest.json"]);
});
test("generated drift rejected", () =>
  assert.throws(() =>
    checkBundle({ readGenerated: (n) => files[n] + (n === "install.sql" ? "-- drift" : "") }),
  ));
test("expected generated bytes accepted", () =>
  assert.equal(checkBundle({ readGenerated: (n) => files[n] }), true));
test("version2 ready still only returns review ready", () => {
  const r = checkReadiness(plan, observed, now);
  assert.equal(r.status, "REVIEW_READY");
  assert.equal(r.autoApply, false);
});
test("old review hash rejected after source change", () => {
  const changed = JSON.parse(
    renderBundle((p) => (p === sources[0] ? "-- change\n" : "") + read(p))["manifest.json"],
  );
  assert.ok(checkReadiness(changed, observed, now).blocked.includes("BUNDLE_REVIEW_REQUIRED"));
});
test("unreviewed full bundle rejected", () =>
  assert.ok(
    checkReadiness(plan, { ...observed, bundleReviewed: false }, now).blocked.includes(
      "BUNDLE_REVIEW_REQUIRED",
    ),
  ));
test("collision confirmation required", () =>
  assert.ok(
    checkReadiness(plan, { ...observed, deploymentCollisionFree: false }, now).blocked.includes(
      "TARGET_INSPECTION_REQUIRED",
    ),
  ));
test("stale target inspection rejected", () =>
  assert.ok(
    checkReadiness(plan, { ...observed, targetInspectedAt: "2026-11-01T00:00:00Z" }, now).blocked.includes(
      "TARGET_INSPECTION_REQUIRED",
    ),
  ));
test("private schema exposure must be reviewed", () =>
  assert.ok(
    checkReadiness(plan, { ...observed, dataApiPrivateSchemasHidden: false }, now).blocked.includes(
      "PRIVATE_SCHEMA_EXPOSURE_REVIEW_REQUIRED",
    ),
  ));
test("metadata schema scope cannot be replaced", () =>
  assert.ok(
    checkReadiness({ ...plan, metadataSchema: "public" }, observed, now).blocked.includes(
      "BUNDLE_SCOPE_CHANGED",
    ),
  ));
test("additional table scope rejected", () =>
  assert.ok(
    checkReadiness(
      { ...plan, objects: { ...plan.objects, tables: [...plan.objects.tables, "auth.users"] } },
      observed,
      now,
    ).blocked.includes("BUNDLE_SCOPE_CHANGED"),
  ));
test("template list includes read-only target and ACL checks", () => {
  assert.ok(templates.includes("preinstall"));
  assert.ok(templates.includes("verify"));
});

test("unexpected SQL in output folder is rejected", () =>
  assert.throws(() =>
    checkBundle({
      readGenerated: (n) => files[n],
      listGenerated: () => [...Object.keys(files), "unexpected.sql"],
    }),
  ));

test("SQL phase defers unavailable future runtime and file traffic checks", () => {
  const o = {
    ...observed,
    gatewayVerified: false,
    privateStorageVerified: false,
    remainingBytes: { database: 10485760, storage: null, egress: null },
  };
  const r = checkReadiness(plan, o, now, { phase: "sql-install" });
  assert.equal(r.status, "REVIEW_READY");
  assert.equal(r.autoApply, false);
  assert.equal(r.phase, "sql-install");
  assert.ok(r.deferred.includes("GATEWAY_RUNTIME_VALIDATION"));
  assert.equal(checkReadiness(plan, o, now).status, "BLOCKED");
});
test("SQL phase still requires measured DB headroom and owner review", () => {
  const r = checkReadiness(
    plan,
    { ...observed, migrationOwnerReviewed: false, remainingBytes: { database: null } },
    now,
    { phase: "sql-install" },
  );
  assert.ok(r.blocked.includes("INSUFFICIENT_DATABASE_HEADROOM"));
  assert.ok(r.blocked.includes("MIGRATION_OWNER_REVIEWED_REQUIRED"));
});
test("unknown bundle phase cannot bypass checks", () =>
  assert.ok(checkReadiness(plan, observed, now, { phase: "other" }).blocked.includes("PHASE_NOT_SUPPORTED")));
